# Zadanie 1 – definicja funkcji

def doubler(x):
    return 2 * x

print(doubler(3))     # int
print(doubler(3.5))   # float
print(doubler("3"))   # string
# To jest program definiujący funkcję 'doubler', która przyjmuje jeden argument i zwraca jego podwojoną wartość. Funkcja działa dla różnych typów danych, takich jak liczby całkowite, liczby zmiennoprzecinkowe oraz łańcuchy tekstowe (stringi).